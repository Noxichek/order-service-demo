// package main говорит Go, что этот файл — точка входа для создания исполняемой программы.
// Каждое приложение на Go должно начинаться с пакета main.
package main

// Импорт (подключение) других пакетов с кодом.
// Всё, что до пустой строки — это стандартная библиотека Go (идёт вместе с языком).
// Всё, что после — наши собственные внутренние пакеты, которые мы написали специально для этого сервиса.
import (
    "context"      // Позволяет передавать сигналы отмены и дедлайны между горутинами
    "log"           // Простой вывод сообщений в консоль (журнал)
    "net/http"      // Встроенный веб-сервер, который умеет слушать порты и обрабатывать HTTP-запросы
    "os"            // Взаимодействие с операционной системой (сигналы, переменные окружения и т.д.)
    "os/signal"     // Обработка сигналов ОС, например Ctrl+C
    "syscall"        // Конкретные коды сигналов (SIGINT, SIGTERM)
    "time"           // Работа со временем (задержки, таймауты)

    // Ниже — наши собственные пакеты, которые мы создали внутри папки internal.
    // Они находятся в модуле order-service (см. go.mod).
    "order-service/internal/config"    // Чтение настроек (порт, адрес базы и Kafka)
    "order-service/internal/store"     // Работа с базой данных PostgreSQL (сохранение и загрузка заказов)
    "order-service/internal/cache"     // Хранение заказов в оперативной памяти для быстрого доступа
    "order-service/internal/kafka"     // Получение сообщений из очереди Kafka
    "order-service/internal/handler"   // Обработчик HTTP-запросов (наш API)
    "order-service/internal/model"     // Описание структуры данных "Заказ" (как выглядит заказ)
)

// main — главная функция, с которой начинается выполнение любой программы на Go.
func main() {
    // ------------------------------------------------------------
    // Шаг 1. Загружаем настройки (конфигурацию) из переменных окружения.
    // cfg — переменная, в которой будут храниться все нужные параметры.
    cfg := config.Load()

    // ------------------------------------------------------------
    // Шаг 2. Создаём "контекст" с возможностью отмены.
    // Контекст — это специальный объект, который сообщает всем подсистемам,
    // когда пришло время останавливаться (например, при завершении программы).
    // context.Background() — самый корневой контекст, как чистый лист.
    // WithCancel возвращает новый контекст и функцию cancel.
    // Когда мы вызовем cancel(), все, кто слушает ctx, поймут, что пора заканчивать.
    ctx, cancel := context.WithCancel(context.Background())
    // defer — "отложенный вызов". То, что написано после defer, выполнится
    // прямо перед выходом из функции main (в самом конце, при любом return или панике).
    // Здесь мы гарантируем, что cancel будет вызван, и контекст освободит ресурсы.
    defer cancel()

    // ------------------------------------------------------------
    // Шаг 3. Подключаемся к базе данных PostgreSQL.
    // NewStore пытается создать пул соединений и проверить связь (пинг).
    // Она возвращает два значения: указатель на Store и ошибку.
    st, err := store.NewStore(ctx, cfg.DBDSN)
    // В Go принято сразу проверять ошибку. Если err не равна nil — что-то пошло не так.
    if err != nil {
        // log.Fatalf печатает сообщение в консоль и завершает программу с ошибкой.
        log.Fatalf("failed to connect to database: %v", err)
    }
    // defer st.Close() гарантирует, что перед выходом из main мы закроем пул соединений с БД.
    defer st.Close()

    // ------------------------------------------------------------
    // Шаг 4. Создаём кэш (временное хранилище в оперативной памяти).
    c := cache.New()
    // Прогреваем кэш: загружаем все заказы из базы данных, чтобы они были готовы к моментальной выдаче.
    // LoadFromDB принимает функцию, которая возвращает список заказов.
    // Мы передаём анонимную функцию (лямбду), которая вызывает st.GetAllOrders(ctx).
    // st.GetAllOrders возвращает срез (массив) заказов и ошибку.
    if err := c.LoadFromDB(func() ([]*model.Order, error) {
        return st.GetAllOrders(ctx)
    }); err != nil {
        // Если при загрузке произошла ошибка, мы не падаем, а просто пишем предупреждение.
        // Кэш может остаться пустым, но сервис продолжит работать, подгружая заказы по одному при запросах.
        log.Printf("warning: failed to load cache from DB: %v", err)
    }

    // ------------------------------------------------------------
    // Шаг 5. Запускаем слушатель очереди Kafka.
    // NewConsumer создаёт потребителя, который будет читать сообщения из указанного топика.
    // "order-service-group" — идентификатор группы потребителей (если запустим несколько копий сервиса,
    // они будут распределять сообщения между собой).
    // Мы передаём store (st) и кэш (c), чтобы consumer мог сохранять заказы в БД и обновлять кэш.
    consumer := kafka.NewConsumer(cfg.KafkaBroker, cfg.KafkaTopic, "order-service-group", st, c)
    // Запускаем consumer в отдельной горутине (лёгком потоке).
    // Он начинает слушать сообщения, парсить их и сохранять.
    consumer.Start(ctx)
    // Гарантируем, что при завершении программы мы закроем consumer (освободим соединение с Kafka).
    defer consumer.Close()

    // ------------------------------------------------------------
    // Шаг 6. Настраиваем HTTP-сервер для обработки API-запросов.
    // Создаём обработчик (handler), который знает о store и cache.
    h := handler.New(st, c)
    // mux (мультиплексор) — это маршрутизатор: он направляет входящий HTTP-запрос к нужной функции.
    mux := http.NewServeMux()
    // Регистрируем правило: если путь начинается с "/order/", то вызывать метод h.GetOrder.
    // Внутри GetOrder извлекает ID заказа из URL (например, /order/123).
    mux.HandleFunc("/order/", h.GetOrder)

    // Создаём объект HTTP-сервера, указывая адрес (порт) и наш маршрутизатор.
    srv := &http.Server{
        Addr:    ":" + cfg.HTTPPort,  // ":" + "8081" означает слушать порт 8081 на всех сетевых интерфейсах
        Handler: mux,                 // какой обработчик использовать для всех запросов
    }

    // ------------------------------------------------------------
    // Шаг 7. Обработка мягкого завершения работы (graceful shutdown).
    // Запускаем анонимную функцию в отдельной горутине.
    // Она будет ждать сигнал от ОС, и когда сигнал придёт, начнёт аккуратно останавливать сервер.
    go func() {
        // Создаём канал для приёма сигналов от ОС с буфером размером 1.
        sigCh := make(chan os.Signal, 1)
        // signal.Notify говорит: "пересылай в канал sigCh сигналы SIGINT и SIGTERM".
        // SIGINT — это нажатие Ctrl+C в терминале, SIGTERM — команда kill (без -9).
        signal.Notify(sigCh, syscall.SIGINT, syscall.SIGTERM)
        // Блокируем выполнение горутины, пока в канал не придёт сигнал.
        <-sigCh // как только сигнал получен, идём дальше
        log.Println("shutting down...") // Сообщаем в лог, что начали остановку

        // Вызываем cancel(), чтобы отменить наш глобальный контекст.
        // Это приведёт к тому, что consumer Kafka остановит чтение, активные операции прервутся.
        cancel()

        // Создаём новый контекст с таймаутом 5 секунд.
        // За это время сервер должен завершить обработку текущих запросов.
        shutdownCtx, shutdownCancel := context.WithTimeout(context.Background(), 5*time.Second)
        defer shutdownCancel() // гарантируем, что таймаут будет отменён после выхода из этой анонимной функции

        // Вызываем Shutdown — это вежливая остановка HTTP-сервера:
        // перестаём принимать новые соединения, но ждём завершения уже начатых запросов.
        srv.Shutdown(shutdownCtx)
        // Если за 5 секунд запросы не завершились, Shutdown завершится с ошибкой по таймауту.
    }()

    // ------------------------------------------------------------
    // Шаг 8. Запускаем HTTP-сервер и пишем об этом в лог.
    log.Printf("HTTP server listening on port %s", cfg.HTTPPort)
    // ListenAndServe блокирует главную горутину и начинает слушать порт.
    // Как только вызывается srv.Shutdown, ListenAndServe возвращает http.ErrServerClosed.
    if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
        // Если ошибка другая (не связанная с вежливой остановкой) — это фатальная проблема.
        log.Fatalf("server error: %v", err)
    }
    // Сюда мы попадаем после того, как сервер успешно остановился.
    log.Println("server stopped")
}